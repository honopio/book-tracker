-- Drop existing tables
DROP TABLE IF EXISTS public.book_user CASCADE;
DROP TABLE IF EXISTS public.books CASCADE;

------------------------ TABLES ----------------------------

-- Books table
CREATE TABLE public.books (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
  title CHARACTER VARYING NOT NULL,
  author CHARACTER VARYING NULL,
  CONSTRAINT books_pkey PRIMARY KEY (id)
) TABLESPACE pg_default;

-- Book-User junction table
CREATE TABLE public.book_user (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
  book_id BIGINT NOT NULL,
  user_id UUID NOT NULL,
  status CHARACTER VARYING NOT NULL,
  rating NUMERIC(2,1) NULL,
  page_count BIGINT NULL,
  current_page BIGINT NULL,
  progress BIGINT NULL,
  comment TEXT NULL,
  CONSTRAINT book_user_pkey PRIMARY KEY (id),
  CONSTRAINT book_user_unique UNIQUE (book_id, user_id),
  CONSTRAINT book_user_book_id_fkey FOREIGN KEY (book_id) REFERENCES books (id) ON UPDATE CASCADE ON DELETE CASCADE,
  CONSTRAINT book_user_user_id_fkey FOREIGN KEY (user_id) REFERENCES auth.users (id) ON UPDATE CASCADE ON DELETE CASCADE
) TABLESPACE pg_default;

------------------------ CONSTRAINTS ----------------------------

ALTER TABLE book_user ADD CONSTRAINT status_check
  CHECK (status IN ('reading', 'want-to-read', 'finished'));

ALTER TABLE book_user ADD CONSTRAINT rating_check
  CHECK (rating BETWEEN 0 AND 5 OR rating IS NULL);

ALTER TABLE book_user ADD CONSTRAINT page_count_check
  CHECK (page_count >= 0 OR page_count IS NULL);

ALTER TABLE book_user ADD CONSTRAINT current_page_check
  CHECK (current_page >= 0 OR current_page IS NULL);

ALTER TABLE book_user ADD CONSTRAINT progress_check
  CHECK (progress BETWEEN 0 AND 100 OR progress IS NULL);

------------------------ TRIGGERS ----------------------------

-- Set progress based on status
CREATE OR REPLACE FUNCTION set_progress_based_on_status()
RETURNS TRIGGER AS $$
BEGIN
    IF NEW.status = 'finished' THEN
        NEW.progress := 100;
    ELSIF NEW.status = 'reading' THEN
        IF NEW.progress >= 100 OR NEW.progress IS NULL THEN
            NEW.progress := 0;
        END IF;
    ELSIF NEW.status = 'want-to-read' THEN
        NEW.progress := 0;
    ELSE
        NEW.progress := NULL;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_set_progress ON book_user;
CREATE TRIGGER trg_set_progress
BEFORE INSERT OR UPDATE ON book_user
FOR EACH ROW
EXECUTE FUNCTION set_progress_based_on_status();

-- Calculate progress from page count and current page
CREATE OR REPLACE FUNCTION set_progress_from_pages()
RETURNS TRIGGER AS $$
BEGIN
    IF NEW.page_count IS NOT NULL AND NEW.current_page IS NOT NULL AND NEW.page_count > 0 THEN
        NEW.progress := ROUND(NEW.current_page * 100.0 / NEW.page_count);
    ELSIF NEW.status = 'reading' THEN
        NEW.progress := 0;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_set_progress_from_pages ON book_user;
CREATE TRIGGER trg_set_progress_from_pages
BEFORE INSERT OR UPDATE ON book_user
FOR EACH ROW
EXECUTE FUNCTION set_progress_from_pages();

-- Force set rating to NULL for 'want-to-read' status
CREATE OR REPLACE FUNCTION set_rating_null_for_want_to_read()
RETURNS TRIGGER AS $$
BEGIN
    IF NEW.status = 'want-to-read' THEN
        NEW.rating := NULL;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_set_rating_null ON book_user;
CREATE TRIGGER trg_set_rating_null
BEFORE INSERT OR UPDATE ON book_user
FOR EACH ROW
EXECUTE FUNCTION set_rating_null_for_want_to_read();

-- If book is finished, set current page to page count
CREATE OR REPLACE FUNCTION set_current_page_to_page_count()
RETURNS TRIGGER AS $$
BEGIN
    IF NEW.status = 'finished' AND NEW.page_count IS NOT NULL THEN
        NEW.current_page := NEW.page_count;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_set_current_page ON book_user;
CREATE TRIGGER trg_set_current_page
BEFORE INSERT OR UPDATE ON book_user
FOR EACH ROW
EXECUTE FUNCTION set_current_page_to_page_count();

