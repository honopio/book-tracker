------------------------ POLICIES ----------------------------

-- Books are public (can be shared across users)
CREATE POLICY "Anyone can view books" ON books
  FOR SELECT USING (true);

CREATE POLICY "Authenticated users can insert books" ON books
  FOR INSERT WITH CHECK (auth.role() = 'authenticated');

-- Book-user relationships are private to each user
CREATE POLICY "Users can view own book relationships" ON book_user
  FOR SELECT USING (auth.uid() = user_id);

CREATE POLICY "Users can insert own book relationships" ON book_user
  FOR INSERT WITH CHECK (auth.uid() = user_id);

CREATE POLICY "Users can update own book relationships" ON book_user
  FOR UPDATE USING (auth.uid() = user_id);

CREATE POLICY "Users can delete own book relationships" ON book_user
  FOR DELETE USING (auth.uid() = user_id);

CREATE POLICY "Anyone can view demo user's books" ON book_user
  FOR SELECT USING (user_id = '00000000-0000-0000-0000-000000000000');


